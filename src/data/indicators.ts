const fechaDescarga = deptosData.meta.descargado.slice(0, 10);
const losAndes = filas.find((f) => f.departamento === "Los Andes")!;
const total = filas.reduce(
  (a, f) => ({ pob: a.pob + f.poblacion_2022, salud: a.salud + f.establecimientos_salud, edu: a.edu + f.establecimientos_educativos }),
  { pob: 0, salud: 0, edu: 0 }
);
const round1 = (n: number) => Math.round(n * 10) / 10;
export const provincia = {
  poblacion: total.pob,
  saludCada10k: round1((total.salud / total.pob) * 1e4),
  eduCada10k: round1((total.edu / total.pob) * 1e4),
};

